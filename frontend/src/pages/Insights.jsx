import { useState } from 'react'
import { AlertTriangle, CheckCircle2, Info, Lightbulb, Sparkles } from 'lucide-react'
import { api, monthLabel } from '../api'
import { Empty, ErrorState, Skeleton, useApi, useToast } from '../ui'

const ICON = { warning: AlertTriangle, success: CheckCircle2, info: Info, tip: Lightbulb }

export default function Insights() {
  const toast = useToast()
  const [month, setMonth] = useState(new Date().toISOString().slice(0, 7))
  const { data, loading, error, reload } = useApi('/insights?month=' + month)
  const [ai, setAi] = useState(null); const [busy, setBusy] = useState(false)
  const run = async () => {
    setBusy(true)
    try { setAi(await api(`/insights/ai-summary?month=${month}`, { method: 'POST' })) } catch (e) { toast(e.message, 'err') } finally { setBusy(false) }
  }
  return <>
    <header className="page-head"><div><h1>Insights</h1><p className="muted">Calculated from your transactions for {monthLabel(month)}</p></div>
      <input type="month" value={month} onChange={(e) => { if (e.target.value) { setMonth(e.target.value); setAi(null) } }} aria-label="Month" /></header>
    {data?.ai_available && <section className="card ai"><div className="row"><h2><Sparkles size={18} /> AI summary</h2>
      <button className="btn primary" onClick={run} disabled={busy}>{busy ? 'Writing…' : ai ? 'Regenerate' : 'Generate summary'}</button></div>
      {ai ? <><p className="prewrap">{ai.summary}</p><p className="muted small">Written by {ai.model} from your totals, categories and the insights below. Not financial advice.</p></>
        : <p className="muted">Generated by an AI model from your aggregated figures only; titles and notes of individual transactions are not sent.</p>}</section>}
    {error && !data ? <ErrorState message={error} retry={reload} /> : !data ? <Skeleton h={300} /> : !data.insights.length ?
      <Empty title="Not enough data for insights" text="Add transactions for this month and insights will be calculated automatically." /> :
      <div className={'insights' + (loading ? ' busy' : '')}>{data.insights.map((i, k) => { const I = ICON[i.type]
        return <article className={'card insight ' + i.type} key={k}><I size={20} /><div><h3>{i.title}</h3><p>{i.detail}</p></div></article> })}</div>}
    <p className="muted small foot">These insights come from deterministic rules applied to your own data. {data && !data.ai_available && 'The AI summary is switched off because no AI key is configured on the server.'}</p>
  </>
}
